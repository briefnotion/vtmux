#!/usr/bin/env python3
"""Generates src/width_table.inc: the ranges of characters that take no cell (combining marks, zero-width) and two cells
(East Asian wide and fullwidth, emoji), from Python's wcwidth package, which follows the current Unicode tables.
Run it when a new Unicode comes out:   python3 tools/gen_width.py > src/width_table.inc"""
import sys
import wcwidth

def ranges(pred):
    out = []
    start = None
    prev = None
    for cp in range(0x20, 0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            ok = False
        else:
            ok = pred(cp)
        if ok and start is None:
            start = cp
        if not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out

zero = ranges(lambda cp: wcwidth.wcwidth(chr(cp)) == 0)
wide = ranges(lambda cp: wcwidth.wcwidth(chr(cp)) == 2)

print("// Generated by tools/gen_width.py from Python's wcwidth %s (Unicode %s). Do not edit." % (wcwidth.__version__, wcwidth.list_versions()[-1]))
print("// Ranges of code points, low and high, in order.")
for name, rs in (("ZERO_WIDTH", zero), ("WIDE", wide)):
    print("static const char32_t %s[][2] = {" % name)
    line = "   "
    for lo, hi in rs:
        item = " {0x%X, 0x%X}," % (lo, hi)
        if len(line) + len(item) > 118:
            print(line)
            line = "   "
        line += item
    print(line)
    print("};")
